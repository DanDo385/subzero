"""Checking a bundle of files before any of it is stored."""

from __future__ import annotations

from subzero.artifacts.keys import sanitize_relative_path
from subzero.artifacts.manifest import MANIFEST_FILENAME
from subzero.config import Settings
from subzero.errors import ValidationError


def normalize_bundle(files: dict[str, bytes], settings: Settings) -> dict[str, bytes]:
    """Every path made safe and every size checked, or a ValidationError.

    Runs over the whole bundle first, so a bad file fails before anything is
    written rather than halfway through.
    """
    if not files:
        raise ValidationError("An artifact needs at least one file.")
    if len(files) > settings.max_bundle_files:
        raise ValidationError(
            f"{len(files)} files exceeds the limit of {settings.max_bundle_files} per artifact."
        )
    normalized: dict[str, bytes] = {}
    for raw_path, data in files.items():
        safe_path = sanitize_relative_path(raw_path)
        if safe_path == MANIFEST_FILENAME:
            raise ValidationError(
                f"{MANIFEST_FILENAME} is generated by this service and cannot be supplied."
            )
        if len(data) > settings.max_artifact_file_bytes:
            raise ValidationError(
                f"{safe_path} is {len(data)} bytes, above the per-file limit of "
                f"{settings.max_artifact_file_bytes}."
            )
        normalized[safe_path] = data

    total = sum(len(d) for d in normalized.values())
    if total > settings.max_bundle_bytes:
        raise ValidationError(
            f"Artifact totals {total} bytes, above the limit of {settings.max_bundle_bytes}."
        )

    return normalized
