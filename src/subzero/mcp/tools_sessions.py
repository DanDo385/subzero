"""Live session lifecycle: open on the first prompt, update as you go.

A chat the model is having right now has no platform conversation id the
model can see, so the server mints the session instead: session_open once
per chat, then the returned id on every later call. session_update appends
raw transcript (cheap: no classification, no embeddings inline), and
session_list shows what is live across providers for resuming elsewhere.
"""

from __future__ import annotations

from typing import Annotated, Any
from uuid import UUID

from fastmcp import FastMCP
from fastmcp.server.auth import require_scopes
from pydantic import Field

from subzero.audit.service import AuditService
from subzero.auth import scopes
from subzero.auth.principal import current_principal
from subzero.mcp.compact import dump
from subzero.mcp.result import ToolResult, object_output_schema, text_and_structured
from subzero.sessions.service import SessionService


def register(mcp: FastMCP, *, audit: AuditService, sessions: SessionService) -> None:
    @mcp.tool(
        name="session_open",
        tags={"sessions", "write"},
        auth=require_scopes(scopes.SESSIONS_WRITE),
        annotations={
            "readOnlyHint": False,
            "destructiveHint": False,
            "idempotentHint": True,
            "openWorldHint": False,
        },
        output_schema=object_output_schema(),
    )
    async def session_open(
        provider: Annotated[
            str,
            Field(
                description="Which app or harness you are: chatgpt, claude, gemini, grok or muse."
            ),
        ],
        client_session_id: Annotated[
            str,
            Field(
                description=(
                    "One id for this chat, generated by you (a UUID). Pass it back on every "
                    "later call. Calling open twice with the same id returns the same session."
                )
            ),
        ],
        title: Annotated[str | None, Field(description="Short title for the session.")] = None,
        model: Annotated[str | None, Field(description="Model name, for the record.")] = None,
    ) -> ToolResult:
        """Open this chat's session in Subzero, on the first prompt.

        Call once per chat, before anything else needs the past: it creates
        the conversation row and hands back its id. Keep passing that id to
        session_update, session_checkpoint and session_close for the rest of
        the chat. A second call with the same client_session_id returns the
        same session instead of duplicating it.
        """
        session_id, created = await sessions.open_session(
            provider=provider,
            client_session_id=client_session_id,
            title=title,
            model=model,
        )
        await audit.record(
            tool="session_open",
            action="create" if created else "open",
            object_type="conversation",
            object_id=session_id,
            principal=current_principal(),
        )
        payload = {"session_id": str(session_id), "created": created}
        line = f"session {session_id} {'created' if created else 'already open'}"
        return text_and_structured(line, dump(payload))

    @mcp.tool(
        name="session_update",
        tags={"sessions", "write"},
        auth=require_scopes(scopes.SESSIONS_WRITE),
        annotations={
            "readOnlyHint": False,
            "destructiveHint": False,
            "idempotentHint": True,
            "openWorldHint": False,
        },
        output_schema=object_output_schema(),
    )
    async def session_update(
        session_id: Annotated[
            UUID, Field(description="The id session_open returned for this chat.")
        ],
        messages: Annotated[
            list[dict[str, Any]],
            Field(
                description=(
                    "New transcript lines since the last update: each with role "
                    "(user, assistant, system or tool), content, and a stable "
                    "message_id you choose. Repeats with the same message_id "
                    "are skipped, so a retried update never duplicates."
                )
            ),
        ],
    ) -> ToolResult:
        """Append this chat's new messages to its session. Cheap by design.

        Call every few turns with what is new since the last update, both
        sides: it stores the raw transcript that a later session (possibly
        in another app) resumes from. It classifies nothing and embeds
        nothing; session_checkpoint is still where durable state goes.
        """
        inserted = await sessions.append_session_messages(session_id, messages)
        payload: dict[str, Any] = {
            "session_id": str(session_id),
            "inserted": inserted,
        }
        return text_and_structured(f"{inserted} message(s) stored", dump(payload))

    @mcp.tool(
        name="session_list",
        tags={"sessions", "read"},
        auth=require_scopes(scopes.SESSIONS_READ),
        annotations={
            "readOnlyHint": True,
            "destructiveHint": False,
            "idempotentHint": True,
            "openWorldHint": False,
        },
    )
    async def session_list(
        provider: Annotated[
            str | None, Field(description="Only this app: chatgpt, claude, gemini or grok.")
        ] = None,
        project: Annotated[str | None, Field(description="Only this project (slug).")] = None,
        include_ended: Annotated[
            bool, Field(description="Also show sessions that were closed.")
        ] = False,
        limit: Annotated[int, Field(ge=1, le=50, description="Most sessions to show.")] = 20,
    ) -> list[dict[str, Any]]:
        """Sessions newest-first by last message: who, what, and when.

        Use to resume work started elsewhere: pick a session, then
        context_bootstrap with its project (or session_checkpoint's
        conversation to continue writing to it). Closed sessions stay out
        unless include_ended is set.
        """
        rows = await sessions.list_sessions(
            provider=provider, project=project, include_ended=include_ended, limit=limit
        )
        return [dump({**row, "id": str(row["id"])}) for row in rows]

    @mcp.tool(
        name="session_close",
        tags={"sessions", "write"},
        auth=require_scopes(scopes.SESSIONS_WRITE),
        annotations={
            "readOnlyHint": False,
            "destructiveHint": False,
            "idempotentHint": True,
            "openWorldHint": False,
        },
        output_schema=object_output_schema(),
    )
    async def session_close(
        session_id: Annotated[
            UUID, Field(description="The id session_open returned for this chat.")
        ],
        reason: Annotated[
            str | None, Field(description="Why it ended: done, abandoned, handed off.")
        ] = None,
    ) -> ToolResult:
        """Close this chat's session, like hanging up.

        Call at goodbye when the work is done (or handed to another app, so
        it stops showing as live). Closing twice is fine. It marks the row;
        it summarises nothing — checkpoint first if anything durable was
        decided.
        """
        closed = await sessions.close_session(session_id, reason=reason)
        await audit.record(
            tool="session_close",
            action="close",
            object_type="conversation",
            object_id=session_id,
            principal=current_principal(),
        )
        payload: dict[str, Any] = {"session_id": str(session_id), "closed": closed}
        line = f"session {session_id} closed" if closed else f"no session {session_id}"
        return text_and_structured(line, dump(payload))
