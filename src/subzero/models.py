class Base(BaseModel):
    model_config = ConfigDict(extra="forbid")


BridgeRole = Literal["user", "assistant", "system", "tool"]


class BridgeSessionCreate(Base):
    provider: str = "firstmate"
    title: str | None = None
    model: str | None = None


class BridgeMessageCreate(Base):
    text: str
    role: BridgeRole = "assistant"
    model: str | None = None


class BridgeMessage(Base):
    """One message shown by the browser session bridge."""

    id: UUID
    role: BridgeRole
    content: str
    model: str | None = None
    sequence: int
    created_at: datetime


class BridgeSession(Base):
    """The browser-visible metadata and ordered messages for a bridge."""

    session_id: UUID
    provider: str
    title: str | None = None
    model: str | None = None
    messages: list[BridgeMessage] = Field(default_factory=list)


class BridgeSessionCreated(Base):
    session_id: UUID
    provider: str
    title: str | None = None
    model: str | None = None
    link: str


class BridgeMessageCreated(Base):
    message_id: UUID
    session_id: UUID
    status: Literal["created", "duplicate"]
    sequence: int


# ------------------------------------------------------------------ results


class Provenance_(Base):
    """Where a returned piece of context came from.

    Always attached to retrieval results so the reading model can tell your
    own words apart from another model's conclusions.
    """

    kind: Provenance
    provider: str | None = None
    conversation_id: UUID | None = None
    recorded_at: datetime | None = None
    confidence: float | None = None


class ContextItem(Base):
    """One retrieved item in a context package."""

    type: Literal[
        "memory",
        "summary",
        "decision",
        "project",
        "task",
        "note",
        "message",
        "artifact",
    ]
    id: UUID
    title: str | None = None
    content: str
    score: float | None = None
    project: str | None = None
    provenance: Provenance_
    estimated_tokens: int = 0
    #: When it was decided, or last updated. Ranking uses it; on the wire it
    #: is provenance.recorded_at, so it is not sent twice.
    effective_at: datetime | None = Field(default=None, exclude=True)
    #: Which bootstrap layer returned it: handoff, relevant or raw.
    layer: str | None = None
    #: The note section a meaning-search hit matched, e.g. "Plan > Risks".
    #: Absent for whole-item matches.
    section: str | None = None
    #: "superseded" (with the id that replaced it) for a decision that was
    #: replaced. Absent for live items.
    status: str | None = None
    superseded_by: UUID | None = None
    #: Newer items on the same subject that may overrule this one. Ask the user.
    conflicts_with: list[UUID] = Field(default_factory=list)
    #: Session summaries: questions left open in that session.
    open_questions: list[str] = Field(default_factory=list)
    #: Why this item is here when that is not obvious (e.g. an untagged session).
    reason: str | None = None
    #: Retrieval confidence for the query that found this item: "low" means
    #: nothing matched every query term (and, where meaning search ran, the
    #: closest meaning match was weak), so try different terms. Always set on
    #: items from a search; handoff items carry none.
    retrieval_confidence: Literal["ok", "low"] | None = None


class ProjectCandidate(Base):
    slug: str
    name: str
    reason: str


class ProjectChoice(Base):
    """Which project the package is about, and how that was decided."""

    slug: str | None = None
    name: str | None = None
    #: given (the caller passed it), inferred (read from the query), none.
    source: Literal["given", "inferred", "none"]
    reason: str
    #: Set when the query could mean more than one project.
    candidates: list[ProjectCandidate] = Field(default_factory=list)


class LayerReport(Base):
    name: str
    status: Literal["ran", "skipped"]
    #: Why a layer was skipped, or anything notable about how it ran.
    reason: str | None = None
    items: int | None = None


class ConflictReport(Base):
    """Two items on the same subject where the newer may overrule the older."""

    kind: Literal["superseded", "possible_conflict"]
    #: Older first, newer second.
    ids: list[UUID]
    #: Each side's text, only when that item is not among the items.
    older: str | None = None
    newer: str | None = None
    newer_provenance: str
    advice: str


class AgentContext(Base):
    """One of the owner's dotfiles context documents (see agent_context.py)."""

    document: Literal["context", "soul", "agents", "memory", "machines"]
    path: str
    source: Literal["local", "github"]
    sha256: str
    #: First 12 hex digits of sha256: short enough for a chat to quote back.
    content_id: str
    content: str
    truncated: bool = False


class ContextPackage(Base):
    """Compact package returned by context_bootstrap / context_for_topic."""

    query: str
    #: Standing context from dotfiles (header, SOUL, chat AGENTS, memory,
    #: machines), sent on top of token_budget. Empty when the server has no
    #: dotfiles source. A long machines file is cut to the standing cap.
    standing: list[AgentContext] = Field(default_factory=list)
    items: list[ContextItem] = Field(default_factory=list)
    token_budget: int
    estimated_tokens: int
    layers_used: list[str] = Field(default_factory=list)
    truncated: bool = False
    notes: list[str] = Field(default_factory=list)
    #: The search terms actually used, after dropping filler words.
    keywords: list[str] = Field(default_factory=list)
    project: ProjectChoice | None = None
    #: Every layer, including the ones skipped, with the reason.
    layers: list[LayerReport] = Field(default_factory=list)
    conflicts: list[ConflictReport] = Field(default_factory=list)


